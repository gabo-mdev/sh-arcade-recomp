#!/usr/bin/env python3
"""Generate a C dispatcher stub for covered 6809 PCs (static recomp scaffold).

Full instruction lifting lands incrementally; this emits a callable skeleton
that falls back to the interpreter for unknown PCs.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "gen" / "main_recomp.cpp"


HEADER = r'''// Auto-generated by tools/transpile.py — do not edit.
#include "cpu/m6809.hpp"
#include <cstdint>

namespace sh::recomp {

// Returns true if the PC was handled natively.
bool main_try_recompiled(sh::M6809& cpu);

} // namespace sh::recomp
'''

SOURCE_HEAD = r'''// Auto-generated by tools/transpile.py — do not edit.
#include "cpu/m6809.hpp"
#include <cstdint>

namespace sh::recomp {

bool main_try_recompiled(sh::M6809& cpu) {
  switch (cpu.pc) {
'''

SOURCE_TAIL = r'''  default:
    return false;
  }
}

} // namespace sh::recomp
'''


def main() -> int:
    static_path = ROOT / "analysis" / "static.json"
    entries = []
    if static_path.exists():
        data = json.loads(static_path.read_text(encoding="utf-8"))
        for fn in data.get("functions", []):
            entries.append(int(fn["entry"], 16))
    entries = sorted(set(entries))[:256]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    (OUT.parent / "main_recomp.hpp").write_text(HEADER, encoding="utf-8")
    body = [SOURCE_HEAD]
    for pc in entries:
        body.append(f"  case 0x{pc:04X}:\n")
        body.append("    // TODO: lifted block\n")
        body.append("    return false;\n")
    body.append(SOURCE_TAIL)
    OUT.write_text("".join(body), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} case stubs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
